import assert from "node:assert/strict";
import test from "node:test";
import { mkdtemp, mkdir, readFile, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";

import { AMUX_V22_WORKTREE_TMP, ensureAmuxV22WorktreeDependencies } from
  "../lib/amux/v22WorkerDependencies.mjs";

async function checkout() {
  const root = await mkdtemp(join(tmpdir(), "amux-v22-deps-"));
  await writeFile(join(root, "package-lock.json"), '{"lockfileVersion":3}\n');
  return root;
}

test("a worker checkout gets its locked packages once per lockfile, from the sidecar's home", async () => {
  const root = await checkout();
  try {
    const calls = [];
    const run = async (binary, args, options) => {
      calls.push({ binary, args, options });
      if (binary === "npm")
        await mkdir(join(options.cwd, "node_modules", "prisma", "build"), { recursive: true })
          .then(() => writeFile(join(options.cwd, "node_modules", "prisma", "build", "index.js"), ""));
      return { stdout: "", stderr: "" };
    };
    const first = await ensureAmuxV22WorktreeDependencies(root, "/var/lib/sidecar-home", { run });
    assert.deepEqual(first, { ok: true, installed: true });
    // No package's install script runs where the sidecar's sign-in is readable;
    // the Prisma client is generated by the locked prisma package itself.
    assert.deepEqual(calls.map((call) => [call.binary, ...call.args.slice(0, 2)]),
      [["npm", "ci", "--ignore-scripts"], ["node", "node_modules/prisma/build/index.js", "generate"]]);
    assert.equal(calls[0].options.cwd, root);
    // Only a fixed environment: no token or proxy of the sidecar leaks into npm.
    for (const call of calls) assert.deepEqual(call.options.env,
      { HOME: "/var/lib/sidecar-home", PATH: "/usr/bin:/bin", LANG: "C.UTF-8" });
    // The temp directory the Codex sandbox may write sits inside the ignored tree.
    await readFile(join(root, "node_modules", ".amux-v22-lock-sha256"), "utf8");
    assert.ok(AMUX_V22_WORKTREE_TMP.startsWith("node_modules"));

    const again = await ensureAmuxV22WorktreeDependencies(root, "/var/lib/sidecar-home", { run });
    assert.deepEqual(again, { ok: true, installed: false });
    assert.equal(calls.length, 2);

    // A changed lockfile installs again.
    await writeFile(join(root, "package-lock.json"), '{"lockfileVersion":3,"x":1}\n');
    const changed = await ensureAmuxV22WorktreeDependencies(root, "/var/lib/sidecar-home", { run });
    assert.deepEqual(changed, { ok: true, installed: true });
    assert.equal(calls.length, 4);

    // A new base that changes only the schema (or the Prisma config) keeps
    // the packages but regenerates the client.
    await mkdir(join(root, "prisma"), { recursive: true });
    await writeFile(join(root, "prisma", "schema.prisma"), "model A { id Int @id }\n");
    const schema = await ensureAmuxV22WorktreeDependencies(root, "/var/lib/sidecar-home", { run });
    assert.deepEqual(schema, { ok: true, installed: true });
    assert.deepEqual(calls.slice(4).map((call) => call.binary), ["node"]);
    await writeFile(join(root, "prisma.config.ts"), "export default {};\n");
    await ensureAmuxV22WorktreeDependencies(root, "/var/lib/sidecar-home", { run });
    assert.deepEqual(calls.slice(5).map((call) => call.binary), ["node"]);
    const settled = await ensureAmuxV22WorktreeDependencies(root, "/var/lib/sidecar-home", { run });
    assert.deepEqual(settled, { ok: true, installed: false });
    assert.equal(calls.length, 6);

    // A client that failed to generate is retried alone on the next run.
    await writeFile(join(root, "prisma", "schema.prisma"), "model B { id Int @id }\n");
    const failing = await ensureAmuxV22WorktreeDependencies(root, "/var/lib/sidecar-home", {
      run: async () => { throw Object.assign(new Error("generate"), { code: 1 }); } });
    assert.deepEqual(failing, { ok: false, reason: "install_failed" });
    await ensureAmuxV22WorktreeDependencies(root, "/var/lib/sidecar-home", { run });
    assert.deepEqual(calls.slice(6).map((call) => call.binary), ["node"]);
  } finally { await rm(root, { recursive: true, force: true }); }
});

test("a failed or timed-out install is reported, never thrown, and leaves no marker", async () => {
  const root = await checkout();
  try {
    const failed = await ensureAmuxV22WorktreeDependencies(root, "/h", {
      run: async () => { throw Object.assign(new Error("npm ERR"), { code: 1 }); } });
    assert.deepEqual(failed, { ok: false, reason: "install_failed" });
    const timedOut = await ensureAmuxV22WorktreeDependencies(root, "/h", {
      run: async () => { throw Object.assign(new Error("killed"), { killed: true }); } });
    assert.deepEqual(timedOut, { ok: false, reason: "install_timed_out" });
    // An install without the prisma package cannot generate the client.
    const noPrisma = await ensureAmuxV22WorktreeDependencies(root, "/h",
      { run: async () => ({ stdout: "", stderr: "" }) });
    assert.deepEqual(noPrisma, { ok: false, reason: "install_failed" });
    await assert.rejects(readFile(join(root, "node_modules", ".amux-v22-lock-sha256")));
    const noLock = await ensureAmuxV22WorktreeDependencies(join(root, "missing"), "/h",
      { run: async () => assert.fail("no install without a lockfile") });
    assert.deepEqual(noLock, { ok: false, reason: "no_lockfile" });
    assert.deepEqual(await ensureAmuxV22WorktreeDependencies("relative", "/h"),
      { ok: false, reason: "invalid_input" });
  } finally { await rm(root, { recursive: true, force: true }); }
});
