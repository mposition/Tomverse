import assert from "node:assert/strict";
import { execFileSync } from "node:child_process";
import { existsSync } from "node:fs";
import test from "node:test";
import { mkdtemp, mkdir, readdir, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";

import { AMUX_V22_PINNED_NPM_CLI, AMUX_V22_WORKTREE_TMP, ensureAmuxV22WorktreeDependencies } from
  "../lib/amux/v22WorkerDependencies.mjs";
import { removeAmuxV22WorktreeLeftovers } from "../lib/amux/v22PatchCapture.mjs";

// The system npm path; the pinned-npm test covers the other.
const none = () => false;

async function checkout() {
  const root = await mkdtemp(join(tmpdir(), "amux-v22-deps-"));
  await writeFile(join(root, "package-lock.json"), '{"lockfileVersion":3}\n');
  return root;
}

const installer = (calls) => async (binary, args, options) => {
  calls.push({ binary, args, options });
  if (binary === "npm" || args[1] === "ci")
    await mkdir(join(options.cwd, "node_modules", "prisma", "build"), { recursive: true })
      .then(() => writeFile(join(options.cwd, "node_modules", "prisma", "build", "index.js"), ""));
  return { stdout: "", stderr: "" };
};

test("every implement attempt removes earlier leftovers, then installs and generates afresh", async () => {
  // Review r-20261109-014107-dd07b1: the install runs outside any sandbox, so
  // nothing an earlier attempt left (.env, .npmrc, node_modules, a marker)
  // may shape it.
  const root = await checkout();
  try {
    const calls = [];
    const order = [];
    const run = installer(calls);
    const removeLeftovers = async (path) => { order.push(["clean", path]); };
    for (let attempt = 0; attempt < 2; attempt += 1) {
      const result = await ensureAmuxV22WorktreeDependencies(root, "/var/lib/sidecar-home",
        { run: async (...args) => { order.push([args[0], args[1][0]]); return run(...args); },
          exists: none, removeLeftovers });
      assert.deepEqual(result, { ok: true, installed: true });
    }
    // Same lockfile, second attempt: still cleaned and installed again.
    assert.deepEqual(order, [["clean", root], ["npm", "ci"],
      ["node", "node_modules/prisma/build/index.js"],
      ["clean", root], ["npm", "ci"], ["node", "node_modules/prisma/build/index.js"]]);
    // No package's install script runs where the sidecar's sign-in is readable;
    // the Prisma client is generated by the fresh prisma package itself.
    assert.deepEqual(calls[0].args.slice(0, 2), ["ci", "--ignore-scripts"]);
    assert.equal(calls[0].options.cwd, root);
    // Only a fixed environment: no token or proxy of the sidecar leaks into npm.
    for (const call of calls) assert.deepEqual(call.options.env,
      { HOME: "/var/lib/sidecar-home", PATH: "/usr/bin:/bin", LANG: "C.UTF-8" });
    // The sandboxes' writable temp directory sits inside the ignored tree.
    assert.ok(AMUX_V22_WORKTREE_TMP.startsWith("node_modules"));
    assert.ok(existsSync(join(root, AMUX_V22_WORKTREE_TMP)));
    // No install marker is written or read any more.
    assert.deepEqual((await readdir(join(root, "node_modules"))).sort(), [".cache", "prisma"]);
  } finally { await rm(root, { recursive: true, force: true }); }
});

test("the rollout's pinned npm runs the install when it is there", async () => {
  // Ubuntu's npm 9.2.0 refuses the lockfile's nested workspace (2026-11-09).
  const root = await checkout();
  try {
    const calls = [];
    const seen = [];
    const result = await ensureAmuxV22WorktreeDependencies(root, "/h",
      { run: installer(calls), removeLeftovers: async () => {},
        exists: (path) => { seen.push(path); return true; } });
    assert.deepEqual(result, { ok: true, installed: true });
    assert.deepEqual(seen, [AMUX_V22_PINNED_NPM_CLI]);
    assert.ok(AMUX_V22_PINNED_NPM_CLI.startsWith("/opt/tomverse-amux-v22/"));
    assert.deepEqual([calls[0].binary, ...calls[0].args.slice(0, 3)],
      ["node", AMUX_V22_PINNED_NPM_CLI, "ci", "--ignore-scripts"]);
  } finally { await rm(root, { recursive: true, force: true }); }
});

test("a failed clean, install or generate is reported, never thrown", async () => {
  const root = await checkout();
  const removeLeftovers = async () => {};
  try {
    // Leftovers that could not be removed stop the install before npm runs.
    const notCleaned = await ensureAmuxV22WorktreeDependencies(root, "/h", { exists: none,
      removeLeftovers: async () => { throw new Error("git"); },
      run: async () => assert.fail("no install over leftovers") });
    assert.deepEqual(notCleaned, { ok: false, reason: "leftovers_not_removed" });
    const failed = await ensureAmuxV22WorktreeDependencies(root, "/h", { exists: none,
      removeLeftovers, run: async () => { throw Object.assign(new Error("npm ERR"), { code: 1 }); } });
    assert.deepEqual(failed, { ok: false, reason: "install_failed" });
    const timedOut = await ensureAmuxV22WorktreeDependencies(root, "/h", { exists: none,
      removeLeftovers, run: async () => { throw Object.assign(new Error("killed"), { killed: true }); } });
    assert.deepEqual(timedOut, { ok: false, reason: "install_timed_out" });
    // An install without the prisma package cannot generate the client.
    const noPrisma = await ensureAmuxV22WorktreeDependencies(root, "/h",
      { exists: none, removeLeftovers, run: async () => ({ stdout: "", stderr: "" }) });
    assert.deepEqual(noPrisma, { ok: false, reason: "install_failed" });
    const noLock = await ensureAmuxV22WorktreeDependencies(join(root, "missing"), "/h",
      { removeLeftovers: async () => assert.fail("nothing to clean"),
        run: async () => assert.fail("no install without a lockfile") });
    assert.deepEqual(noLock, { ok: false, reason: "no_lockfile" });
    assert.deepEqual(await ensureAmuxV22WorktreeDependencies("relative", "/h"),
      { ok: false, reason: "invalid_input" });
  } finally { await rm(root, { recursive: true, force: true }); }
});

test("leftover removal deletes every untracked and ignored file and keeps tracked ones", {
  skip: process.platform !== "linux" || !existsSync("/usr/bin/git") ? "needs /usr/bin/git" : false,
}, async () => {
  const root = await mkdtemp(join(tmpdir(), "amux-v22-leftovers-"));
  try {
    const git = (...args) => execFileSync("/usr/bin/git", ["-C", root, ...args],
      { stdio: "ignore", env: { PATH: "/usr/bin:/bin", HOME: root } });
    git("init", "-q");
    await writeFile(join(root, ".gitignore"), "node_modules/\n.env\nartifacts/\n");
    await writeFile(join(root, "prisma.config.ts"), "import \"dotenv/config\";\n");
    git("add", ".");
    git("-c", "user.name=t", "-c", "user.email=t@example.invalid", "commit", "-qm", "base");
    await mkdir(join(root, "node_modules", "prisma", "build"), { recursive: true });
    await writeFile(join(root, "node_modules", "prisma", "build", "index.js"), "tampered");
    await writeFile(join(root, ".env"), "PRISMA_SCHEMA_ENGINE_BINARY=/x\n");
    await writeFile(join(root, ".npmrc"), "registry=http://127.0.0.1:1/\n");
    await mkdir(join(root, "artifacts"));
    await writeFile(join(root, "artifacts", "engine"), "#!/bin/sh\n");
    await removeAmuxV22WorktreeLeftovers(root);
    assert.deepEqual((await readdir(root)).sort(), [".git", ".gitignore", "prisma.config.ts"]);
  } finally { await rm(root, { recursive: true, force: true }); }
});
