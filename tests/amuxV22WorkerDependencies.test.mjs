import assert from "node:assert/strict";
import { execFileSync } from "node:child_process";
import { existsSync } from "node:fs";
import test from "node:test";
import { lstat, mkdir, mkdtemp, readdir, readFile, rm, symlink, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";

import { AMUX_V22_PINNED_NPM_CLI, AMUX_V22_WORKTREE_TMP, ensureAmuxV22WorktreeDependencies } from
  "../lib/amux/v22WorkerDependencies.mjs";
import { removeAmuxV22WorktreeLeftovers } from "../lib/amux/v22PatchCapture.mjs";

// The leftover clean (a real git test below) and the system npm (the pinned
// npm has its own test) are fixed for the install tests.
const fixed = { removeLeftovers: async () => {}, hasPinnedNpm: () => false };

async function checkout() {
  const root = await mkdtemp(join(tmpdir(), "amux-v22-deps-"));
  await writeFile(join(root, "package-lock.json"), '{"lockfileVersion":3}\n');
  return root;
}

function fakeNpm(calls) {
  return async (binary, args, options) => {
    calls.push({ binary, args, options });
    if (binary === "npm") {
      await mkdir(join(options.cwd, "node_modules", "prisma", "build"), { recursive: true });
      await writeFile(join(options.cwd, "node_modules", "prisma", "build", "index.js"), "");
    }
    return { stdout: "", stderr: "" };
  };
}

test("every attempt reinstalls the locked packages from scratch, from the sidecar's home", async () => {
  const root = await checkout();
  try {
    const calls = [];
    const run = fakeNpm(calls);
    assert.deepEqual(await ensureAmuxV22WorktreeDependencies(root, "/var/lib/sidecar-home", { ...fixed, run }),
      { ok: true });
    // No package's install script runs where the sidecar's sign-in is readable;
    // the Prisma client is generated by the freshly installed prisma package.
    assert.deepEqual(calls.map((call) => [call.binary, ...call.args.slice(0, 2)]),
      [["npm", "ci", "--ignore-scripts"], ["node", "node_modules/prisma/build/index.js", "generate"]]);
    for (const call of calls) {
      assert.equal(call.options.cwd, root);
      // Only a fixed environment: no token or proxy of the sidecar leaks into npm.
      assert.deepEqual(call.options.env,
        { HOME: "/var/lib/sidecar-home", PATH: "/usr/bin:/bin", LANG: "C.UTF-8" });
    }
    await lstat(join(root, AMUX_V22_WORKTREE_TMP));
    assert.ok(AMUX_V22_WORKTREE_TMP.startsWith("node_modules"));

    // A file an earlier Codex run left (or changed) under node_modules is gone
    // before anything runs: nothing installed earlier is trusted.
    await writeFile(join(root, "node_modules", "prisma", "build", "index.js"), "tampered");
    await writeFile(join(root, "node_modules", "left-behind.js"), "x");
    const seen = [];
    await ensureAmuxV22WorktreeDependencies(root, "/var/lib/sidecar-home", {
      ...fixed, run: async (binary, args, options) => {
        if (binary === "npm") {
          seen.push(await readFile(join(options.cwd, "node_modules", "left-behind.js"))
            .then(() => "present", () => "removed"));
        }
        return run(binary, args, options);
      } });
    assert.deepEqual(seen, ["removed"]);
    assert.equal(await readFile(join(root, "node_modules", "prisma", "build", "index.js"), "utf8"), "");
    assert.equal(calls.filter((call) => call.binary === "npm").length, 2);
  } finally { await rm(root, { recursive: true, force: true }); }
});

test("a node_modules symlink is removed as a link, never followed", { skip: process.platform === "win32" }, async () => {
  const root = await checkout();
  const outside = await mkdtemp(join(tmpdir(), "amux-v22-outside-"));
  try {
    await writeFile(join(outside, "keep.txt"), "keep");
    await symlink(outside, join(root, "node_modules"));
    await ensureAmuxV22WorktreeDependencies(root, "/h", { ...fixed, run: fakeNpm([]) });
    assert.equal(await readFile(join(outside, "keep.txt"), "utf8"), "keep");
    assert.ok((await lstat(join(root, "node_modules"))).isDirectory());
  } finally {
    await rm(root, { recursive: true, force: true });
    await rm(outside, { recursive: true, force: true });
  }
});

test("a failed or timed-out install is reported, never thrown", async () => {
  const root = await checkout();
  try {
    const failed = await ensureAmuxV22WorktreeDependencies(root, "/h", {
      ...fixed, run: async () => { throw Object.assign(new Error("npm ERR"), { code: 1 }); } });
    assert.deepEqual(failed, { ok: false, reason: "install_failed" });
    const timedOut = await ensureAmuxV22WorktreeDependencies(root, "/h", {
      ...fixed, run: async () => { throw Object.assign(new Error("killed"), { killed: true }); } });
    assert.deepEqual(timedOut, { ok: false, reason: "install_timed_out" });
    // An install without the prisma package cannot generate the client.
    const calls = [];
    const noPrisma = await ensureAmuxV22WorktreeDependencies(root, "/h",
      { ...fixed, run: async (binary) => { calls.push(binary); return { stdout: "", stderr: "" }; } });
    assert.deepEqual(noPrisma, { ok: false, reason: "install_failed" });
    assert.deepEqual(calls, ["npm"]);
    const noLock = await ensureAmuxV22WorktreeDependencies(join(root, "missing"), "/h",
      { ...fixed, run: async () => assert.fail("no install without a lockfile") });
    assert.deepEqual(noLock, { ok: false, reason: "no_lockfile" });
    assert.deepEqual(await ensureAmuxV22WorktreeDependencies("relative", "/h"),
      { ok: false, reason: "invalid_input" });
  } finally { await rm(root, { recursive: true, force: true }); }
});

test("the rollout's pinned npm runs the install when it is there", async () => {
  // Ubuntu's npm 9.2.0 refuses the lockfile's nested workspace (2026-11-09).
  const root = await checkout();
  try {
    const calls = [];
    const seen = [];
    const run = async (binary, args, options) => {
      calls.push([binary, ...args.slice(0, 3)]);
      if (args[1] === "ci") {
        await mkdir(join(options.cwd, "node_modules", "prisma", "build"), { recursive: true });
        await writeFile(join(options.cwd, "node_modules", "prisma", "build", "index.js"), "");
      }
      return { stdout: "", stderr: "" };
    };
    const result = await ensureAmuxV22WorktreeDependencies(root, "/h", { ...fixed, run,
      hasPinnedNpm: (path) => { seen.push(path); return true; } });
    assert.deepEqual(result, { ok: true });
    assert.deepEqual(seen, [AMUX_V22_PINNED_NPM_CLI]);
    assert.ok(AMUX_V22_PINNED_NPM_CLI.startsWith("/opt/tomverse-amux-v22/"));
    assert.deepEqual(calls[0], ["node", AMUX_V22_PINNED_NPM_CLI, "ci", "--ignore-scripts"]);
  } finally { await rm(root, { recursive: true, force: true }); }
});

test("every ignored file an earlier attempt left is removed first, or nothing runs", async () => {
  // Review r-20261109-014107-dd07b1: a .env that prisma.config.ts loads, an
  // .npmrc or an artifacts/ binary is not under node_modules.
  const root = await checkout();
  try {
    const order = [];
    const result = await ensureAmuxV22WorktreeDependencies(root, "/h", { ...fixed,
      removeLeftovers: async (path) => { order.push(["clean", path]); },
      run: async (binary, args, options) => { order.push([binary]); return fakeNpm([])(binary, args, options); } });
    assert.deepEqual(result, { ok: true });
    assert.deepEqual(order, [["clean", root], ["npm"], ["node"]]);
    const notCleaned = await ensureAmuxV22WorktreeDependencies(root, "/h", { ...fixed,
      removeLeftovers: async () => { throw new Error("git"); },
      run: async () => assert.fail("no install over leftovers") });
    assert.deepEqual(notCleaned, { ok: false, reason: "leftovers_not_removed" });
  } finally { await rm(root, { recursive: true, force: true }); }
});

test("leftover removal deletes every untracked and ignored file and keeps tracked ones", {
  skip: process.platform !== "linux" || !existsSync("/usr/bin/git") ? "needs /usr/bin/git" : false,
}, async () => {
  const root = await mkdtemp(join(tmpdir(), "amux-v22-leftovers-"));
  try {
    const git = (...args) => execFileSync("/usr/bin/git", ["-C", root, ...args],
      { stdio: "ignore", env: { PATH: "/usr/bin:/bin", HOME: root } });
    git("init", "-q");
    await writeFile(join(root, ".gitignore"), "node_modules/\n.env\nartifacts/\n");
    await writeFile(join(root, "prisma.config.ts"), "import \"dotenv/config\";\n");
    git("add", ".");
    git("-c", "user.name=t", "-c", "user.email=t@example.invalid", "commit", "-qm", "base");
    await mkdir(join(root, "node_modules", "prisma", "build"), { recursive: true });
    await writeFile(join(root, "node_modules", "prisma", "build", "index.js"), "tampered");
    await writeFile(join(root, ".env"), "PRISMA_SCHEMA_ENGINE_BINARY=/x\n");
    await writeFile(join(root, ".npmrc"), "registry=http://127.0.0.1:1/\n");
    await mkdir(join(root, "artifacts"));
    await writeFile(join(root, "artifacts", "engine"), "#!/bin/sh\n");
    await removeAmuxV22WorktreeLeftovers(root);
    assert.deepEqual((await readdir(root)).sort(), [".git", ".gitignore", "prisma.config.ts"]);
  } finally { await rm(root, { recursive: true, force: true }); }
});
