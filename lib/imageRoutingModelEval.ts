export type ImageEvalPick = { modelId: string; preset: ImagePreset };

export type ImageEvalRunCandidate = {
  model: ImageModelProfile;
  /** The categories the model fits, when known; absent means every category. */
  categories?: readonly string[];
};

export type ImageEvalCost = {
  kind: "image" | "judge";
  provider: string;
  modelId: string;
  /** The amount to count: the real cost when known, the worst case when not. */
  microUsd: number;
  known: boolean;
};

/** What a paid call in the evaluation is, for the caller's budget. */
export type ImageEvalPaidCall = { kind: "image"; provider: string; modelId: string } | { kind: "judge" };

export type RunImageModelEvalInput = {
  requests: readonly SyntheticImageRequest[];
  /** The current criteria's choice for a request; null or an unknown model fails the case. */
  pickFor: (request: SyntheticImageRequest) => ImageEvalPick | null | Promise<ImageEvalPick | null>;
  candidates: readonly ImageEvalRunCandidate[];
  judgeModel: AiModel;
  callModel?: EvalLanguageModelFactory;
  generate?: (input: GenerateEvalImageInput) => Promise<GenerateEvalImageResult>;
  judge?: (input: JudgeImagePairInput) => Promise<JudgeImagePairResult>;
  /**
   * Checked before every paid call with that call's worst case in micro-USD
   * and what it is: an image (its provider, so the caller can reserve that
   * provider's budget) or the judged pair. False stops the run; a call already
   * made is not interrupted.
   */
  shouldContinue: (worstCaseMicroUsd: number, call: ImageEvalPaidCall) => boolean | Promise<boolean>;
  /** Called after every paid call, including a failed one, so cost is recorded as it accrues. */
  onCost: (cost: ImageEvalCost) => void | Promise<void>;
  /** Worst case of one judged pair (both vision calls), micro-USD. Default 0. */
  judgeWorstCaseMicroUsd?: number;
  /** The judge's token prices, micro-USD per token (USD per million tokens). Without them a judge call is reported as unknown cost at its worst case. */
  judgeUsdPerMillionTokens?: { input: number; output: number };
  signal?: AbortSignal;
  onCase?: (evalCase: ImageEvalCase) => void | Promise<void>;
};

export type RunImageModelEvalResult = {
  cases: ImageEvalCase[];
  /** shouldContinue said no (or the signal aborted) before a paid call. */
  stopped: boolean;
  /** Requests not started or not finished because the run stopped. */
  unfinished: number;
};

const sideOf = (modelId: string, generated: GenerateEvalImageResult | null): ImageEvalSide => ({
  modelId,
  generated: generated?.ok === true,
  costMicroUsd: generated?.ok === true ? generated.costMicroUsd : null,
  durationMs: generated?.ok === true ? generated.durationMs : null,
});

/**
 * Runs each request: the router's pick and a challenger each make an image, a
 * vision model judges the pair in both orders, and every case comes back as a
 * win, loss, tie or failure for the pick (summarizeImageModelEval reads them).
 * Requests run one at a time. The challenger is another candidate that fits
 * the request's category with the cost closest to the pick's at the same
 * preset; a model that cannot offer that preset uses its nearest quality.
 *
 * Budget: before each image and each judged pair, shouldContinue receives that
 * call's worst case, and false ends the run. A run that stops after the pick's
 * image leaves that image unpaired (it was paid for and is reported through
 * onCost; no case is recorded for it). A model with no bounded price is never
 * called and fails its case.
 */
export const runImageModelEval = async (input: RunImageModelEvalInput): Promise<RunImageModelEvalResult> => {
  const generate = input.generate ?? generateEvalImage;
  const judge = input.judge ?? judgeImagePair;
  const cases: ImageEvalCase[] = [];
  let stopped = false;
  const record = async (evalCase: ImageEvalCase) => {
    cases.push(evalCase);
    await input.onCase?.(evalCase);
  };
  const allowed = async (worstCase: number, call: ImageEvalPaidCall) =>
    !input.signal?.aborted && (await input.shouldContinue(worstCase, call)) === true;
  const modelById = (id: string) => input.candidates.find((candidate) => candidate.model.id === id) ?? null;

  const failedCase = (
    request: SyntheticImageRequest,
    pick: ImageEvalSide,
    challenger: ImageEvalSide | null,
    failure: ImageEvalCaseFailure
  ): ImageEvalCase => ({ category: request.category, pick, challenger, outcome: "failed", failure });

  /** Makes one image under the budget. `null` means the run stopped before the call. */
  const makeImage = async (
    model: ImageModelProfile,
    request: SyntheticImageRequest,
    preset: ImagePreset
  ): Promise<GenerateEvalImageResult | null> => {
    const worst = imageWorstCaseMicroUsd(model, preset);
    if (worst === null) {
      return {
        ok: false,
        failure: "unpriced",
        message: `No bounded price for ${model.id}.`,
        modelId: model.id,
        provider: model.provider,
        durationMs: 0,
        costMicroUsd: 0,
        costUnknown: false,
        worstCaseMicroUsd: null,
      };
    }
    if (!(await allowed(worst, { kind: "image", provider: model.provider, modelId: model.id }))) return null;
    let result: GenerateEvalImageResult;
    try {
      result = await generate({ model, prompt: request.text, preset, ...(input.signal ? { signal: input.signal } : {}) });
    } catch (error) {
      result = {
        ok: false,
        failure: "provider_error",
        message: error instanceof Error ? error.message.slice(0, 300) : "Image generation failed.",
        modelId: model.id,
        provider: model.provider,
        durationMs: 0,
        costMicroUsd: null,
        costUnknown: true,
        worstCaseMicroUsd: worst,
      };
    }
    const known = !result.costUnknown && finiteNonNegative(result.costMicroUsd);
    await input.onCost({
      kind: "image",
      provider: model.provider,
      modelId: model.id,
      microUsd: known ? (result.costMicroUsd as number) : (result.worstCaseMicroUsd ?? worst),
      known,
    });
    return result;
  };

  for (let index = 0; index < input.requests.length; index += 1) {
    const request = input.requests[index];
    const pick = await input.pickFor(request);
    const pickCandidate = pick ? modelById(pick.modelId) : null;
    if (!pick || !pickCandidate) {
      await record(
        failedCase(request, sideOf(pick?.modelId ?? "unknown", null), null, {
          stage: "pick",
          modelId: null,
          reason: pick ? "pick_not_a_candidate" : "no_pick",
        })
      );
      continue;
    }

    const challengerCandidates: ImageEvalCandidate[] = input.candidates.map((candidate) => ({
      id: candidate.model.id,
      costMicroUsd: imageEvalOption(candidate.model, pick.preset)?.outputCostMicroUsd ?? null,
      ...(candidate.categories ? { categories: candidate.categories } : {}),
    }));
    const challenger = challengerFor(challengerCandidates, pick.modelId, request.category);
    const challengerCandidate = challenger ? modelById(challenger.id) : null;
    if (!challenger || !challengerCandidate) {
      await record(
        failedCase(request, sideOf(pick.modelId, null), null, {
          stage: "challenger",
          modelId: null,
          reason: "no_challenger",
        })
      );
      continue;
    }

    const pickImage = await makeImage(pickCandidate.model, request, pick.preset);
    if (pickImage === null) {
      stopped = true;
      break;
    }
    if (!pickImage.ok) {
      await record(
        failedCase(request, sideOf(pick.modelId, pickImage), sideOf(challenger.id, null), {
          stage: "generate",
          modelId: pick.modelId,
          reason: pickImage.failure,
        })
      );
      continue;
    }
    const challengerImage = await makeImage(challengerCandidate.model, request, pick.preset);
    if (challengerImage === null) {
      stopped = true;
      break;
    }
    if (!challengerImage.ok) {
      await record(
        failedCase(request, sideOf(pick.modelId, pickImage), sideOf(challenger.id, challengerImage), {
          stage: "generate",
          modelId: challenger.id,
          reason: challengerImage.failure,
        })
      );
      continue;
    }

    const pickSide = sideOf(pick.modelId, pickImage);
    const challengerSide = sideOf(challenger.id, challengerImage);
    const judgeWorst = Math.max(0, input.judgeWorstCaseMicroUsd ?? 0);
    if (!(await allowed(judgeWorst, { kind: "judge" }))) {
      stopped = true;
      break;
    }
    let judged: JudgeImagePairResult;
    try {
      judged = await judge({
        judgeModel: input.judgeModel,
        request: request.text,
        imageA: pickImage.image,
        imageB: challengerImage.image,
        costMicroUsdA: pickImage.costMicroUsd,
        costMicroUsdB: challengerImage.costMicroUsd,
        ...(input.callModel ? { callModel: input.callModel } : {}),
        ...(input.signal ? { signal: input.signal } : {}),
      });
    } catch (error) {
      judged = {
        ok: false,
        failure: "judge_error",
        message: error instanceof Error ? error.message.slice(0, 300) : "The judge failed.",
        inputTokens: 0,
        outputTokens: 0,
        usageUnknown: true,
        calls: 2,
      };
    }
    const prices = input.judgeUsdPerMillionTokens;
    const priced =
      !judged.usageUnknown && prices && finiteNonNegative(prices.input) && finiteNonNegative(prices.output)
        ? Math.ceil(judged.inputTokens * prices.input + judged.outputTokens * prices.output)
        : null;
    if (judged.calls > 0) {
      await input.onCost({
        kind: "judge",
        provider: input.judgeModel.provider,
        modelId: input.judgeModel.id,
        microUsd: priced ?? judgeWorst,
        known: priced !== null,
      });
    }
    if (!judged.ok) {
      await record(
        failedCase(request, pickSide, challengerSide, { stage: "judge", modelId: null, reason: judged.failure })
      );
      continue;
    }
    await record({
      category: request.category,
      pick: pickSide,
      challenger: challengerSide,
      outcome: judged.verdict === "A" ? "pick_win" : judged.verdict === "B" ? "challenger_win" : "tie",
      failure: null,
    });
  }

  return { cases, stopped, unfinished: input.requests.length - cases.length };
};
