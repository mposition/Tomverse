export type GenerateEvalImageInput = {
  model: ImageModelProfile;
  prompt: string;
  preset: ImagePreset;
  /**
   * Stops waiting for the image. The adapter takes no signal, so the provider
   * request itself still runs to its own timeout and may be billed; the result
   * then says so (costUnknown).
   */
  signal?: AbortSignal;
};

type EvalImageBase = {
  modelId: string;
  provider: string;
  durationMs: number;
  /** Micro-USD the image cost, or null when it is not known (see costUnknown). */
  costMicroUsd: number | null;
  /** True when a request may have been billed for an amount this module cannot state. */
  costUnknown: boolean;
  /** The ceiling of this one call, for budgeting an unknown cost; null when the call was never priceable. */
  worstCaseMicroUsd: number | null;
};

export type GenerateEvalImageResult =
  | (EvalImageBase & {
      ok: true;
      image: EvalImage;
      quality: ImageQuality;
      size: string;
    })
  | (EvalImageBase & {
      ok: false;
      failure: "unpriced" | "aborted" | "provider_error";
      message: string;
    });

const ABORTED = Symbol("aborted");

const withAbort = <T>(promise: Promise<T>, signal: AbortSignal | undefined): Promise<T | typeof ABORTED> => {
  // The losing branch must never become an unhandled rejection.
  promise.catch(() => undefined);
  if (!signal) return promise;
  if (signal.aborted) return Promise.resolve(ABORTED);
  return new Promise((resolve, reject) => {
    const onAbort = () => resolve(ABORTED);
    signal.addEventListener("abort", onAbort, { once: true });
    promise.then(
      (value) => {
        signal.removeEventListener("abort", onAbort);
        resolve(value);
      },
      (error) => {
        signal.removeEventListener("abort", onAbort);
        reject(error);
      }
    );
  });
};

const finiteNonNegative = (value: unknown): value is number =>
  typeof value === "number" && Number.isFinite(value) && value >= 0;

/**
 * What a delivered image cost, or null when this module cannot say:
 *   - the provider's own reported cost (xAI), when it gave one;
 *   - otherwise the option's official per-image price, for a provider that
 *     bills no thinking (OpenAI, xAI, Qwen, BFL), plus OpenAI's prompt tokens
 *     at the text input rate;
 *   - the same price plus the flat thinking surcharge the request always incurs
 *     (fal's Nano Banana 2);
 *   - null for a provider that bills thinking per token (Google), whose real
 *     cost the response does not state.
 */
export const deliveredEvalImageCostMicroUsd = (
  model: ImageModelProfile,
  option: ImageModelOptionPrice,
  result: { reportedCostMicroUsd?: number | null; inputTokens: number }
): number | null => {
  if (finiteNonNegative(result.reportedCostMicroUsd)) return result.reportedCostMicroUsd;
  const billing = imageThinkingBilling(model.provider, model.apiModelId, model.billingTerms);
  if (billing === "flat_per_request") {
    const surcharge = imageThinkingCapMinimumMicroUsd(model.provider, model.apiModelId, model.billingTerms);
    return finiteNonNegative(surcharge) ? option.outputCostMicroUsd + surcharge : null;
  }
  if (billing !== "not_billed") return null;
  const prompt =
    model.provider === "openai" && finiteNonNegative(result.inputTokens)
      ? Math.ceil(result.inputTokens * IMAGE_PROMPT_INPUT_USD_PER_MILLION_TOKENS)
      : 0;
  return option.outputCostMicroUsd + prompt;
};

/**
 * Makes one evaluation image through the provider adapter and returns the
 * bytes in memory. No R2 upload, no credit reservation, no user, no budget
 * bucket. Never throws: every failure comes back as `ok: false`.
 *
 * Needs the provider's own key in the environment (OPENAI_IMAGE_API_KEY or the
 * chat OpenAI key, GOOGLE, FAL_KEY, BFL_API_KEY, the Qwen and xAI keys); without
 * it the adapter refuses before any request and the result costs 0. Image
 * editing is not reachable from here. Each image is one request (retry: false),
 * and a failure after the request was sent may still be billed, so it is
 * reported as costUnknown.
 */
export const generateEvalImage = async (input: GenerateEvalImageInput): Promise<GenerateEvalImageResult> => {
  const { model, preset } = input;
  const startedAt = Date.now();
  const worstCaseMicroUsd = imageWorstCaseMicroUsd(model, preset);
  const base = (costMicroUsd: number | null, costUnknown: boolean): EvalImageBase => ({
    modelId: model.id,
    provider: model.provider,
    durationMs: Date.now() - startedAt,
    costMicroUsd,
    costUnknown,
    worstCaseMicroUsd,
  });
  const option = imageEvalOption(model, preset);
  if (worstCaseMicroUsd === null || !option) {
    return { ...base(0, false), ok: false, failure: "unpriced", message: `No bounded price for ${model.id}.` };
  }
  if (input.signal?.aborted) {
    return { ...base(0, false), ok: false, failure: "aborted", message: "Aborted before the request." };
  }
  try {
    const outcome = await withAbort(
      generateImageWithProvider({
        prompt: input.prompt,
        size: option.size,
        quality: option.quality,
        modelId: model.id,
        // One request: the reported cost is then the whole cost, and the
        // caller's hold settles to it (lib/imageRoutingOptimizer.ts).
        retry: false,
      }),
      input.signal
    );
    if (outcome === ABORTED) {
      // The request was already on its way and may be billed.
      return { ...base(null, true), ok: false, failure: "aborted", message: "Aborted while waiting for the image." };
    }
    const cost = deliveredEvalImageCostMicroUsd(model, option, outcome);
    return {
      ...base(cost, cost === null),
      ok: true,
      image: { bytes: outcome.imageBytes, mimeType: outcome.mimeType },
      quality: option.quality,
      size: option.size,
    };
  } catch (error) {
    // An adapter refusal before a request was built (no key, model not
    // available) carries neither a status nor request parameters and cost
    // nothing; anything else may have been billed.
    const neverSent =
      error instanceof ImageProviderError && error.status === null && error.requestParams === null;
    return {
      ...base(neverSent ? 0 : null, !neverSent),
      ok: false,
      failure: "provider_error",
      message: error instanceof Error ? error.message.slice(0, 300) : "Image generation failed.",
    };
  }
};

