/**
 * Paid half of the image routing model evaluation. Everything here spends the
 * caller's money (one image per generation, two vision calls per judged pair),
 * so the caller owns the budget: pass `shouldContinue` and `onCost` to
 * runImageModelEval and stop when it is spent. Nothing in this file reads or
 * writes the database, the user credit ledger, R2 or the provider budget
 * buckets; the generated bytes live in memory only.
 *
 * Ground rules, each of which keeps a failure from costing silently:
 *   - a call that was not made costs 0 and says so;
 *   - a call that was made and failed, or whose cost is not stated by the
 *     provider's own price list, is reported with known=false and the worst
 *     case, so a budget counts it at the dearer reading;
 *   - nothing here retries, except the provider adapter's own transport retry
 *     (see generateEvalImage).
 */

export type EvalImage = {
  bytes: Uint8Array;
  mimeType: string;
};

// ---------------------------------------------------------------------------
// Options and worst case
// ---------------------------------------------------------------------------

const QUALITY_ORDER: readonly ImageQuality[] = ["low", "medium", "high"];
const EVAL_SIZE = "1024x1024";

/**
 * The priced option an evaluation image uses for a preset: 1024x1024 where the
 * model sells it, at the preset's quality, or the nearest quality the model
 * offers (cheaper first on a tie). Null when the model has no price at all.
 */
export const imageEvalOption = (model: ImageModelProfile, preset: ImagePreset): ImageModelOptionPrice | null => {
  const square = model.prices.filter((price) => price.size === EVAL_SIZE);
  const pool = square.length > 0 ? square : model.prices;
  if (pool.length === 0) return null;
  const want = QUALITY_ORDER.indexOf(IMAGE_QUALITY_BY_PRESET[preset]);
  return [...pool].sort(
    (a, b) =>
      Math.abs(QUALITY_ORDER.indexOf(a.quality) - want) - Math.abs(QUALITY_ORDER.indexOf(b.quality) - want) ||
      a.outputCostMicroUsd - b.outputCostMicroUsd
  )[0];
};

/** The adapter's own refusal rule: held for price or cost, not for an operator hold. */
const modelCallable = (model: ImageModelProfile) =>
  model.prices.length > 0 && (model.disabledReason === null || model.disabledReason === "operational_hold");

/**
 * The most one image of this model at this preset can cost, micro-USD: the
 * option's official output price, the full prompt budget and the model's proven
 * thinking cap (maxImageRequestCostMicroUsd, the figure the credit price and
 * the provider budget floor are derived from). Null when there is no such
 * price or the worst case is unbounded; a null is never called.
 */
export const imageWorstCaseMicroUsd = (model: ImageModelProfile, preset: ImagePreset): number | null => {
  if (!modelCallable(model)) return null;
  const option = imageEvalOption(model, preset);
  return option ? maxImageRequestCostMicroUsd(model, option) : null;
};

