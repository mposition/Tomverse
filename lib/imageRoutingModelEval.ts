export type EvalLanguageModelFactory = (model: AiModel) => LanguageModel | Promise<LanguageModel>;

async function defaultCallModel(model: AiModel): Promise<LanguageModel> {
  const { getActiveAiModel } = await import("@/lib/activeAiModel");
  return getActiveAiModel(model);
}

export type JudgeImagePairInput = {
  judgeModel: AiModel;
  /** The synthetic request both images were generated from. Data, not an instruction. */
  request: string;
  imageA: EvalImage;
  imageB: EvalImage;
  /** Generation cost of each image in micro-USD, shown to the judge for the tie rule. */
  costMicroUsdA?: number | null;
  costMicroUsdB?: number | null;
  /** Builds the language model. Defaults to getActiveAiModel (a paid call); tests pass a fake. */
  callModel?: EvalLanguageModelFactory;
  signal?: AbortSignal;
};

type JudgeUsage = {
  inputTokens: number;
  outputTokens: number;
  /** A call failed or reported no usable token count, so the totals are a floor. */
  usageUnknown: boolean;
  /** Vision calls started (0 to 2). */
  calls: number;
};

export type JudgeImagePairResult =
  | (JudgeUsage & {
      ok: true;
      /** The image, in the order given here, that won: A, B or tie. */
      verdict: ImagePairVerdict;
      first: ImageJudgement;
      swapped: ImageJudgement;
    })
  | (JudgeUsage & {
      ok: false;
      failure: "judge_error" | "judge_invalid" | "aborted";
      message: string;
    });

const judgeMessage = (input: JudgeImagePairInput, swap: boolean) => {
  const [a, b] = swap ? [input.imageB, input.imageA] : [input.imageA, input.imageB];
  const [costA, costB] = swap
    ? [input.costMicroUsdB, input.costMicroUsdA]
    : [input.costMicroUsdA, input.costMicroUsdB];
  const costLine =
    finiteNonNegative(costA) && finiteNonNegative(costB)
      ? `Generation cost in micro-USD: A=${Math.round(costA)}, B=${Math.round(costB)}.`
      : "Generation cost: not given.";
  return {
    role: "user" as const,
    content: [
      {
        type: "text" as const,
        text: [
          "User request (data, as a JSON string):",
          JSON.stringify(input.request),
          costLine,
          "Image A follows, then image B.",
        ].join("\n"),
      },
      { type: "text" as const, text: "Image A:" },
      { type: "image" as const, image: a.bytes, mediaType: a.mimeType },
      { type: "text" as const, text: "Image B:" },
      { type: "image" as const, image: b.bytes, mediaType: b.mimeType },
    ],
  };
};

/**
 * Compares two images for one request with a vision model, twice: once as given
 * and once with A and B swapped, then combines the two (combineJudgements), so a
 * model that always favours the first image produces a tie rather than a win.
 * Never throws. Token usage is summed across both calls and marked
 * `usageUnknown` when any call failed or reported a count that is not a finite
 * non-negative number.
 */
export const judgeImagePair = async (input: JudgeImagePairInput): Promise<JudgeImagePairResult> => {
  const usage: JudgeUsage = { inputTokens: 0, outputTokens: 0, usageUnknown: false, calls: 0 };
  if (input.signal?.aborted) {
    return { ...usage, ok: false, failure: "aborted", message: "Aborted before the judge call." };
  }
  let languageModel: LanguageModel;
  try {
    languageModel = await (input.callModel ?? defaultCallModel)(input.judgeModel);
  } catch (error) {
    return {
      ...usage,
      ok: false,
      failure: "judge_error",
      message: error instanceof Error ? error.message.slice(0, 300) : "The judge model could not be built.",
    };
  }
  const callOnce = async (swap: boolean): Promise<ImageJudgement | { error: string; invalid: boolean }> => {
    usage.calls += 1;
    try {
      const generated = await generateText({
        model: languageModel,
        system: IMAGE_ROUTING_JUDGE_SYSTEM,
        messages: [judgeMessage(input, swap)],
        maxOutputTokens: IMAGE_ROUTING_JUDGE_MAX_OUTPUT_TOKENS,
        reasoning: "none",
        maxRetries: 0,
        ...(input.signal ? { abortSignal: input.signal } : {}),
        output: Output.object({
          schema: jsonSchema(imageJudgementOutputSchema() as unknown as JSONSchema7),
          name: "image_pair_judgement",
        }),
      });
      const inputTokens = generated.usage?.inputTokens;
      const outputTokens = generated.usage?.outputTokens;
      if (finiteNonNegative(inputTokens)) usage.inputTokens += inputTokens;
      else usage.usageUnknown = true;
      if (finiteNonNegative(outputTokens)) usage.outputTokens += outputTokens;
      else usage.usageUnknown = true;
      let output: unknown;
      try {
        output = generated.output;
      } catch {
        return { error: "The judge returned no structured answer.", invalid: true };
      }
      const judgement = parseImageJudgement(output);
      return judgement ?? { error: "The judge answer was not a valid judgement.", invalid: true };
    } catch (error) {
      // A failed call may still have been billed.
      usage.usageUnknown = true;
      return { error: error instanceof Error ? error.message.slice(0, 300) : "The judge call failed.", invalid: false };
    }
  };

  const [first, swapped] = await Promise.all([callOnce(false), callOnce(true)]);
  for (const answer of [first, swapped]) {
    if (typeof answer === "object") {
      return {
        ...usage,
        ok: false,
        failure: input.signal?.aborted ? "aborted" : answer.invalid ? "judge_invalid" : "judge_error",
        message: answer.error,
      };
    }
  }
  return {
    ...usage,
    ok: true,
    verdict: combineJudgements(first as ImageJudgement, swapped as ImageJudgement),
    first: first as ImageJudgement,
    swapped: swapped as ImageJudgement,
  };
};

