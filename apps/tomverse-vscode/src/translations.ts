export const localeFor = (value: string): keyof typeof messages => {
    const lang = value.toLowerCase();
    if (["zh-tw", "zh-hk", "zh-hant", "zhhant"].includes(lang)) return "zhHant";
    const base = lang.split("-")[0]!;
    return base in messages ? (base as keyof typeof messages) : "en";
};
