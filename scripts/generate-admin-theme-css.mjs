#!/usr/bin/env node
/**
 * Writes app/(site)/(application)/admin/admin-theme.css from Tailwind's own
 * palette, so the Admin console's Light theme is a remap of the colours the
 * panels already use rather than a second set of classes in every panel.
 *
 *   npm run generate:admin-theme-css
 *
 * tests/adminTheme.test.mjs regenerates it in memory and fails on any drift.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const root = new URL("..", import.meta.url);
const OUT = "app/(site)/(application)/admin/admin-theme.css";

const NEUTRALS = ["zinc", "gray", "slate", "neutral", "stone"];
const HUES = ["red", "orange", "amber", "yellow", "lime", "green", "emerald", "teal", "cyan", "sky",
  "blue", "indigo", "violet", "purple", "fuchsia", "pink", "rose"];
// Dark console step -> the step it is drawn with in Light.
// Neutrals: the page (950) becomes zinc-100 and a card (900) white, as in the
// approved Light mock-up; the rest mirror around 500.
const NEUTRAL_MAP = { 50: 950, 100: 900, 200: 800, 300: 700, 400: 600, 500: 500, 600: 400, 700: 300, 800: 200, 900: "white", 950: 100 };
// Hues: tints and text mirror; 500-700 stay, because they are solid buttons
// and badges that read on either surface.
const HUE_MAP = { 50: 950, 100: 900, 200: 800, 300: 700, 400: 600, 500: 500, 600: 600, 700: 700, 800: 200, 900: 100, 950: 50 };
const SOLID = [500, 600, 700];

export function adminThemeCss(themeCss) {
  const value = (name) => {
    const match = themeCss.match(new RegExp(`--color-${name}:\s*([^;]+);`));
    if (!match) throw new Error(`Tailwind has no --color-${name}`);
    return match[1].trim();
  };
  const lines = [];
  const remap = (family, map) => {
    for (const [step, to] of Object.entries(map)) {
      lines.push(`  --color-${family}-${step}: ${to === "white" ? value("white") : value(`${family}-${to}`)};`);
    }
  };
  for (const family of NEUTRALS) remap(family, NEUTRAL_MAP);
  for (const family of HUES) remap(family, HUE_MAP);
  // Headings are text-white on the dark console; in Light they are ink.
  lines.push(`  --color-white: ${value("zinc-950")};`);
  const solids = HUES.flatMap((hue) => SOLID.map((step) => `[class~="bg-${hue}-${step}"]`));
  return [
    "/* Generated by scripts/generate-admin-theme-css.mjs. Do not edit by hand. */",
    "",
    "/* Native controls and scrollbars follow the console theme: on the shell, and",
    "   on :root and body for a portal outside it (the product theme sets body). */",
    ':root:has([data-admin-theme="dark"]), :root:has([data-admin-theme="dark"]) body, [data-admin-theme="dark"] {',
    "  color-scheme: dark;",
    "}",
    ':root:has([data-admin-theme="light"]) body, [data-admin-theme="light"] {',
    "  color-scheme: light;",
    "}",
    "",
    "/* Light: the same dark-only classes, drawn from a remapped palette. On",
    "   :root so a portal outside the shell is remapped too. */",
    ':root:has([data-admin-theme="light"]) {',
    "  color-scheme: light;",
    ...lines,
    "}",
    "",
    "/* White text on a solid button or badge stays white. */",
    `:root:has([data-admin-theme="light"]) :is(${solids.join(", ")}) {`,
    `  --color-white: ${value("white")};`,
    "}",
    "",
  ].join("\n");
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const themeCss = readFileSync(new URL("node_modules/tailwindcss/theme.css", root), "utf8");
  writeFileSync(new URL(OUT, root), adminThemeCss(themeCss));
  console.log(`wrote ${OUT}`);
}
